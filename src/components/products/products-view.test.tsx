import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { ProductsView } from './products-view'
import { storeAdminSession } from '../../services/admin-session'
import { categoryFixture, categoryPage, jsonResponse, manager } from '../../test/menu-fixtures'

vi.mock('../../services/dish-service', () => ({ dishService: { list: () => Promise.resolve([]) } }))

const defaultProps = { currentUser: manager }

describe('menu category creation', () => {
  it('saves through the backend and immediately adds the returned category to tabs and dish dropdown', async () => {
    const user = userEvent.setup()
    storeAdminSession('test-access', 'test-refresh', manager, true)
    const created = categoryFixture({ id: 27, name: 'Seafood', slug: 'seafood', order: 3, imageUrl: 'https://example.com/seafood.webp' })
    const fetchMock = vi.fn().mockResolvedValueOnce(jsonResponse(categoryPage([categoryFixture()])))
      .mockResolvedValueOnce(jsonResponse(created, 201))
    vi.stubGlobal('fetch', fetchMock)
    const { unmount } = render(<ProductsView {...defaultProps} />)
    await screen.findByRole('button', { name: 'Biryani' })
    await user.click(screen.getByRole('button', { name: 'Add Category' }))
    const dialog = screen.getByRole('dialog', { name: 'Add Category' })
    await user.type(within(dialog).getByLabelText(/Category name/), 'Seafood')
    await user.type(within(dialog).getByLabelText(/Image URL/), 'https://example.com/seafood.webp')
    await user.clear(within(dialog).getByLabelText('Display order'))
    await user.type(within(dialog).getByLabelText('Display order'), '3')
    await user.click(within(dialog).getByRole('button', { name: 'Save Category' }))
    await screen.findByText(/Category “Seafood” saved successfully/)
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(screen.getByRole('button', { name: 'Seafood' })).toBeTruthy()
    const request = JSON.parse(fetchMock.mock.calls[1][1].body)
    expect(request).toEqual({ name: 'Seafood', description: '', imageUrl: created.imageUrl, order: 3, is_active: true })
    expect(request.id).toBeUndefined()
    await user.click(screen.getByRole('button', { name: 'Add New Dish' }))
    const dishDialog = screen.getByRole('dialog', { name: 'Add New Dish' })
    expect(within(dishDialog).getByRole('option', { name: 'Seafood' })).toBeTruthy()
    expect((within(dishDialog).getByLabelText('Category') as HTMLSelectElement).value).toBe('27')
    unmount()
    fetchMock.mockResolvedValueOnce(jsonResponse(categoryPage([categoryFixture(), created])))
    render(<ProductsView {...defaultProps} />)
    expect(await screen.findByRole('button', { name: 'Seafood' })).toBeTruthy()
  })

  it('previews a chosen file and displays the backend image after uploading it', async () => {
    const user = userEvent.setup()
    storeAdminSession('test-access', 'test-refresh', manager, true)
    const created = categoryFixture({ id: 28, name: 'Seafood', imageUrl: 'http://127.0.0.1:8000/media/menu/categories/server-image.webp' })
    const fetchMock = vi.fn().mockResolvedValueOnce(jsonResponse(categoryPage([])))
      .mockResolvedValueOnce(jsonResponse(created, 201))
    vi.stubGlobal('fetch', fetchMock)
    render(<ProductsView {...defaultProps} />)
    await screen.findByText(/No categories yet/)
    await user.click(screen.getByRole('button', { name: 'Add Category' }))
    await user.type(screen.getByLabelText(/Category name/), 'Seafood')
    const image = new File(['image-data'], 'seafood.webp', { type: 'image/webp' })
    await user.upload(screen.getByLabelText('Upload category image'), image)
    expect(screen.getByAltText('Selected category image preview').getAttribute('src')).toMatch(/^blob:/)
    expect(screen.getByText('seafood.webp')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Save Category' }))
    await screen.findByText(/saved successfully/)
    expect(fetchMock.mock.calls[1][1].body.get('image')).toBe(image)
    expect(fetchMock.mock.calls[1][1].body.has('imageUrl')).toBe(false)
    const tab = screen.getByRole('button', { name: 'Seafood' })
    expect(tab.querySelector('img')?.getAttribute('src')).toBe(created.imageUrl)
  })

  it('keeps form input and shows duplicate-name validation without adding a local category', async () => {
    const user = userEvent.setup()
    storeAdminSession('test-access', 'test-refresh', manager, true)
    const fetchMock = vi.fn().mockResolvedValueOnce(jsonResponse(categoryPage([categoryFixture()])))
      .mockResolvedValueOnce(jsonResponse({ name: ['A category with this name already exists.'] }, 400))
    vi.stubGlobal('fetch', fetchMock)
    render(<ProductsView {...defaultProps} />)
    await screen.findByRole('button', { name: 'Biryani' })
    await user.click(screen.getByRole('button', { name: 'Add Category' }))
    await user.type(screen.getByLabelText(/Category name/), 'Biryani')
    await user.click(screen.getByRole('button', { name: 'Save Category' }))
    await waitFor(() => expect(screen.getByLabelText(/Category name/).getAttribute('aria-invalid')).toBe('true'))
    expect((screen.getByLabelText(/Category name/) as HTMLInputElement).value).toBe('Biryani')
    expect(screen.getByRole('dialog')).toBeTruthy()
    expect(screen.queryByText(/saved successfully/)).toBeNull()
    expect(screen.getAllByRole('button', { name: 'Biryani' })).toHaveLength(1)
  })

  it('disables repeat submits until the server confirms success', async () => {
    const user = userEvent.setup()
    storeAdminSession('test-access', 'test-refresh', manager, true)
    let finish: (value: Response) => void = () => { throw new Error('Request did not start') }
    const pending = new Promise<Response>((resolve) => { finish = resolve })
    const fetchMock = vi.fn().mockResolvedValueOnce(jsonResponse(categoryPage([]))).mockReturnValueOnce(pending)
    vi.stubGlobal('fetch', fetchMock)
    render(<ProductsView {...defaultProps} />)
    await screen.findByText(/No categories yet/)
    await user.click(screen.getByRole('button', { name: 'Add Category' }))
    await user.type(screen.getByLabelText(/Category name/), 'Seafood')
    await user.click(screen.getByRole('button', { name: 'Save Category' }))
    expect((screen.getByRole('button', { name: 'Saving category…' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.submit(screen.getByLabelText(/Category name/).closest('form')!)
    expect(fetchMock).toHaveBeenCalledTimes(2)
    finish(jsonResponse(categoryFixture({ name: 'Seafood' }), 201))
    await screen.findByText(/saved successfully/)
  })

  it('shows list failure and can retry successfully without hardcoded category fallback', async () => {
    const user = userEvent.setup()
    vi.stubGlobal('fetch', vi.fn().mockRejectedValueOnce(new TypeError('Offline'))
      .mockResolvedValueOnce(jsonResponse(categoryPage([categoryFixture({ name: 'Live category' })]))))
    render(<ProductsView {...defaultProps} />)
    await screen.findByRole('alert')
    expect(screen.queryByRole('button', { name: 'Biryani' })).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Retry' }))
    expect(await screen.findByRole('button', { name: 'Live category' })).toBeTruthy()
  })

  it('prevents offline preview accounts and unprivileged users from saving categories', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(jsonResponse(categoryPage([]))))
    localStorage.setItem('amber_admin_token', 'offline-manager-token')
    const { unmount } = render(<ProductsView {...defaultProps} />)
    expect((screen.getByRole('button', { name: 'Add Category' }) as HTMLButtonElement).disabled).toBe(true)
    unmount()
    storeAdminSession('real-test-token', 'test-refresh', manager, true)
    render(<ProductsView {...defaultProps} currentUser={{ ...manager, role: 'cashier_front', permissions: [] }} />)
    expect((screen.getByRole('button', { name: 'Add Category' }) as HTMLButtonElement).disabled).toBe(true)
  })
})
